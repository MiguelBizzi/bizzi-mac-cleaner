import { getLocale, hasKey, setLocale, t } from "../core/i18n.js";
import { TARGETS } from "./catalog.js";
import type { SystemDataTarget, TaxonomyGroup } from "./types.js";

/** Declaration order of `TaxonomyGroup`. */
const GROUPS: readonly TaxonomyGroup[] = [
  "user_caches",
  "logs",
  "web_data",
  "developer",
  "ai_models",
  "device_backups",
  "snapshots",
  "virtualization",
  "mail_messages",
  "system_managed",
];

const COLUMNS = [
  "Target",
  "Location",
  "Safety",
  "macOS",
  "Needs FDA",
  "Why",
  "What regenerates it",
  "Impact of removal",
  "Handled by",
] as const;

const cell = (s: string): string => s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
const code = (s: string): string => `<code>${cell(s)}</code>`;

/** Optional locale text: empty when the key is absent (t() would echo the key). */
function text(key: string): string {
  return hasKey(key) ? t(key) : "";
}

function scannerLabel(id: string): string {
  const camel = id.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
  return text(`scanners.${camel}`) || id;
}

function macos(target: SystemDataTarget): string {
  const { min, max } = target.macos ?? {};
  if (min && max) return `${min} to ${max}`;
  if (min) return `${min}+`;
  if (max) return `up to ${max}`;
  return "any";
}

function fda(target: SystemDataTarget): string {
  if (target.fda === "required") return "yes";
  if (target.fda) return `from macOS ${target.fda.fromMacOS}`;
  return "no";
}

function handledBy(target: SystemDataTarget): string {
  if (target.safety === "never") return "never touched";
  if (target.safety === "advisory") return "macOS / owning tool";
  return target.ownedBy ? scannerLabel(target.ownedBy) : "System Data";
}

function locations(target: SystemDataTarget): string {
  return target.patterns.length === 0 ? "n/a" : target.patterns.map(code).join("<br>");
}

function row(target: SystemDataTarget): string {
  const cols = [
    cell(t(`sd.${target.id}.label`)),
    locations(target),
    cell(t(`sd.safety.${target.safety}`)),
    macos(target),
    fda(target),
    cell(text(`sd.${target.id}.why`)),
    cell(text(`sd.${target.id}.regen`)),
    cell(text(`sd.${target.id}.impact`)),
    cell(handledBy(target)),
  ];
  return `| ${cols.join(" | ")} |`;
}

function render(): string {
  const out: string[] = [
    "# System Data taxonomy",
    "",
    "<!-- Generated by `npm run docs:system-data` from src/systemData/catalog.ts and the en locale. Do not edit by hand. -->",
    "",
    "Every location the System Data engine knows about, grouped as in the app. For what the safety levels mean, see the [expert guide](./README.md#the-safety-model).",
    "",
  ];
  for (const level of ["safe", "review", "advisory", "never"] as const) {
    out.push(`- **${t(`sd.safety.${level}`)}**: ${t(`sd.safety.${level}.def`)}`);
  }
  out.push("");
  for (const group of GROUPS) {
    const targets = TARGETS.filter((x) => x.group === group && x.safety !== "never");
    if (targets.length === 0) continue;
    out.push(`## ${t(`sd.group.${group}`)}`, "");
    out.push(`| ${COLUMNS.join(" | ")} |`, `| ${COLUMNS.map(() => "---").join(" | ")} |`);
    for (const target of targets) out.push(row(target));
    out.push("");
  }
  out.push("## Never touched", "", t("sd.safety.never.def"), "");
  for (const target of TARGETS.filter((x) => x.safety === "never")) {
    out.push(`### ${t(`sd.${target.id}.label`)}`, "", text(`sd.${target.id}.why`), "");
    for (const p of target.patterns) out.push(`- <code>${p.replace(/&/g, "&amp;").replace(/</g, "&lt;")}</code>`);
    out.push("");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

/** Deterministic, locale-independent Markdown for docs/system-data/TAXONOMY.md. */
export function renderTaxonomyMarkdown(): string {
  const previous = getLocale();
  setLocale("en");
  try {
    return render();
  } finally {
    setLocale(previous);
  }
}
